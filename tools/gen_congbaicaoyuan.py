def accbox_sub(cat, subs):
    """subs: [(subtitle, [(w,d),...]), ...]"""
    out = ['<div class="box"><div class="acc-cat"><h3>%s</h3>' % cat]
    for sub, items in subs:
        out.append('<div class="acc-sub">%s</div>' % sub)
        for w, d in items:
            out.append('<div class="acc-item"><span class="acc-w">%s</span><span class="acc-d">%s</span></div>' % (w, d))
    out.append('</div></div>')
    return "\n".join(out)

