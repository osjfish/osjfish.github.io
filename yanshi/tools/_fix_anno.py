# 找到 CARDS 列表
start = s.index("CARDS = [")
end = s.index("\n]\n\nPARTS = {")
cards_section = s[start:end]

lines = cards_section.split("\n")
result = []
card_idx = 0

for line in lines:
    m = re.match(r'^(\(\d+, ")(.*)("?,?)$', line)
    if m and card_idx < len(ANNO) and ANNO[card_idx]:
        prefix = m.group(1)
        text = m.group(2)
        suffix = m.group(3)
        for word, note in ANNO[card_idx]:
            if word in text:
                replacement = '" + A("' + word + '","' + note + '") + "'
                text = text.replace(word, replacement, 1)
        line = prefix + text + suffix
        card_idx += 1
    elif re.match(r'^\(\d+, "', line):
        card_idx += 1
    result.append(line)

new_cards = "\n".join(result)
s = s[:start] + new_cards + s[end:]

io.open(p, 'w', encoding='utf-8-sig').write(s)
print("Cleaned and added annotations to %d cards" % card_idx)
