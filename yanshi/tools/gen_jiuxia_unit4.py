def gen_part(part, start_idx):
    """生成一个部分（part-head + overview + cards）"""
    html = f'''      <div class="part-head"><span class="p-num">{part['num']}</span><h3>{part['title']}</h3><span class="range">{part['range']}</span></div>
      <div class="part-overview">{part['overview']}</div>
'''
    for i, para in enumerate(part['paras']):
        html += gen_verse_card(start_idx + i, para) + '\n'
    return html, start_idx + len(part['paras'])

def gen_fulltext(parts):
    """生成背诵区全文"""
    lines = []
    for part in parts:
        for para in part['paras']:
            lines.append(f'    <div class="pl">{strip_anno(para["text"])}</div>')
    return '\n'.join(lines)

