def annotate(text, annotations):
    """按出现顺序插入注释span"""
    result = text
    offset = 0
    for word, note in annotations:
        idx = result.find(word, offset)
        if idx == -1:
            print(f"  WARNING: '{word}' not found")
            continue
        span = f'<span class="anno-word" data-note="{note}">{word}</span>'
        result = result[:idx] + span + result[idx+len(word):]
        offset = idx + len(span)
    return result

def strip_anno(html):
    """去掉注释span，保留纯文本"""
    return re.sub(r'<span class="anno-word"[^>]*>(.*?)</span>', r'\1', html)

def fix_content_quotes(html):
    """将正文文本中的英文直引号替换为中文引号（不处理标签内属性）"""
    def replace_quotes(text):
        result = []
        open_quote = True
        for ch in text:
            if ch == '"':
                if open_quote:
                    result.append('\u201c')
                else:
                    result.append('\u201d')
                open_quote = not open_quote
            else:
                result.append(ch)
        return ''.join(result)
    parts = re.split(r'(<[^>]+>)', html)
    for i in range(len(parts)):
        if not parts[i].startswith('<'):
            parts[i] = replace_quotes(parts[i])
    return ''.join(parts)

def gen_verse_card(idx, para):
    """生成一个解读卡片"""
    anno_text = annotate(para['text'], para.get('annos', []))
