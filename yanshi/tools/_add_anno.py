cards_section = s[start:end]

# 逐行处理：找到每个卡片的原文部分（第一个引号字符串，在部分号之后）
lines = cards_section.split("\n")
result = []
card_idx = 0
in_card = False
for line in lines:
    if line.startswith("(") and re.match(r'\(\d+, "', line):
        # 新卡片开始
        if card_idx < len(ANNO) and ANNO[card_idx]:
            # 在这一行的原文中添加注释
            for word, note in ANNO[card_idx]:
                # 只替换第一次出现（在原文部分）
                if word in line:
                    line = line.replace(word, A(word, note), 1)
        card_idx += 1
    result.append(line)

new_cards = "\n".join(result)
s = s[:start] + new_cards + s[end:]

io.open(p, 'w', encoding='utf-8-sig').write(s)
print("Added annotations to %d cards" % card_idx)
