def annotate(text, zhushi):
    for word, note in sorted(zhushi, key=lambda x: -len(x[0])):
        w = re.sub(r'\([^)]*\)', '', word)
        if w in text:
            text = text.replace(w, f'<span class="anno-word" data-note="{note}">{w}</span>', 1)
    return text

