def annotate(text, annos):
    result = text
    for word, note in annos:
        note_esc = note.replace('"', '&quot;')
        result = result.replace('[['+word+']]',
            '<span class="anno-word" data-note="'+note_esc+'">'+word+'</span>')
    return result

def build_cards():
    parts = []
    idx = 0
    for start, end, pnum, ptitle, prange, poverview in PARTS:
        parts.append('      <div class="part-head"><span class="p-num">'+pnum+'</span><h3>'+ptitle+'</h3><span class="range">'+prange+'</span></div>')
        parts.append('      <div class="part-overview">'+poverview+'</div>')
        for i in range(start, end+1):
            orig, summary, technique, annos = S[i]
            idx += 1
            line_html = annotate(orig, annos)
            card = '      <div class="verse" id="l'+str(idx)+'" data-i="'+str(idx-1)+'">\n'
            card += '        <div class="v-top"><span class="v-no">'+str(idx)+'</span><div class="v-line">'+line_html+'</div></div>\n'
